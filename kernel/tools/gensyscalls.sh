#!/bin/sh
# gensyscalls.sh - write include/sysproto.h: the prototypes of every
# "long sys_NAME(...)" defined in the kernel sources.  Run from the top.
{
  echo '/* generated by tools/gensyscalls.sh: do not edit */'
  cat arch/*.c kern/*.c mm/*.c fs/*.c drivers/*.c |
    awk '/^long sys_[a-z0-9_]*\([^)]*\) \{/ { i = index($0, ")"); print substr($0, 1, i) ";" }'
} > include/sysproto.h
