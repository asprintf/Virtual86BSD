#!/bin/sh
# mkzeta.sh - write src/math/zeta.h: zeta(k) - 1 for k = 2..41, for the
# series of lgamma(2 + t) = (1 - gamma) t + sum (-1)^k (zeta(k) - 1) t^k / k.
# Computed with bc by the Euler-Maclaurin formula (N = 40, 15 Bernoulli terms).
cd "$(dirname "$0")/.." || exit 1
{
	echo '/* Generated by tools/mkzeta.sh; do not edit.  __zm1[k - 2] = zeta(k) - 1. */'
	echo 'static const long double __zm1[] = {'
	bc -l <<'BC' | awk '{ printf "\t%sL,\n", $0 }'
scale = 60
b[1] = 1/6; b[2] = -1/30; b[3] = 1/42; b[4] = -1/30; b[5] = 5/66
b[6] = -691/2730; b[7] = 7/6; b[8] = -3617/510; b[9] = 43867/798
b[10] = -174611/330; b[11] = 854513/138; b[12] = -236364091/2730
b[13] = 8553103/6; b[14] = -23749461029/870; b[15] = 8615841276005/14322
define z(s) {
	auto n, t, j, f, r, m
	m = 40; t = 0
	for (n = 2; n < m; n++) t += 1 / n^s
	t += m^(1 - s) / (s - 1) + 1 / (2 * m^s)
	f = 1; r = s
	for (j = 1; j <= 15; j++) {
		f = f * (2 * j - 1) * (2 * j)
		t += b[j] / f * r / m^(s + 2 * j - 1)
		r = r * (s + 2 * j - 1) * (s + 2 * j)
	}
	return t
}
for (k = 2; k <= 41; k++) { x = z(k); scale = 30; x = x / 1; print x, "\n"; scale = 60 }
BC
	echo '};'
} > src/math/zeta.h
