#!/bin/sh
# bootstrap.sh - build a Virtual/86 BSD system from scratch: the POSIX.1-2024
# utilities and C library of this package, compiled by themselves, in a
# directory that can be entered with chroot (see chroot.sh).
#
# Usage: sh bootstrap.sh [-k] [-n] [-w workdir] [root]
#
#   root        the system to make (default: root/ beside this script); it
#               is made afresh
#   -w workdir  where the stages are built (default: obj/ beside this script)
#   -k          keep workdir afterwards (default: removed when all went well)
#   -n          no stage 3: statically linked programs in the system
#
# What is needed: a POSIX system with a C compiler (CC; without it c17,
# c99 or cc, the first there is),
# make and ar, on x86-64 Linux.  On Ubuntu: build-essential.  Nothing is
# installed outside workdir and root; root needs no privileges to build.
#
# How it goes (each stage is built from a fresh copy of the sources):
#
#   stage 0  The host's compiler builds five tools of this collection,
#            against the host's own C library: c17 (the C compiler, with
#            its own assembler and link editor), make, ar, yacc and lex.
#
#   stage 1  Those tools build everything: the C library (lib/libc/, with c17
#            and make: libc.a, and libc.so, which is also the dynamic
#            linker), then every utility against it (c17 among them),
#            installed into workdir/stage1/root/usr.  From here on no
#            program of the host compiles anything.
#
#   stage 2  The utilities of stage 1, on V86BSD's C library, build
#            everything again (with them on PATH first: c17, make, ar,
#            yacc, lex, sh's helpers, cp, ...), installed into
#            workdir/stage2/root/usr.  The grammars of awk, bc and sh are
#            regenerated by V86BSD's own yacc and lex in every stage.
#            The programs of stages 1 and 2 run on the host, so they are
#            linked statically.
#
#   check    Stage 1 and stage 2 must be identical, file for file (the
#            members of archives compared one by one): c17 compiled by
#            the host's compiler and c17 compiled by itself produce the
#            same programs.  A difference is reported.
#
#   stage 3  The utilities of stage 2 build the utilities once more, for
#            the system: dynamically linked with V86BSD's libc.so (the
#            C library, which is also the dynamic linker,
#            /usr/lib/libc.so) and stripped -- small programs.  The C
#            library installed in root is stage 2's (the same as stage
#            1's).
#
#   kernel   c17 of stage 2 builds the kernel (sys/: c17 compiles its C,
#            assembles its assembly and links it) and init, its first
#            process: root/bsd and root/usr/sbin/init.  The banner of the
#            kernel names who built it, user@host of this machine
#            (BUILDER=user@host in the environment says another: to
#            compare two builds, give both the same).
#
#   system   root gets the rest of a small system: /bin, /lib and /sbin
#            (links to /usr/...), /etc (passwd, group, profile, hosts,
#            services, protocols; from etc/), /tmp, /root, /dev,
#            /proc and /sys (empty: chroot.sh mounts them), /usr/local
#            (for ports/), the host's time zones, terminfo, locale sources
#            and charmaps (for localedef) and certificate
#            authorities (/etc/ssl/certs/ca-certificates.crt), and these
#            sources in /usr/src, so that the system can rebuild
#            itself: inside it, "sh /usr/src/bootstrap.sh /tmp/r"
#            runs the same stages with CC=c17.
#
# Then:   sh chroot.sh root   (with or without root privileges), or on
#         its own kernel in QEMU: sh mkdisk.sh root; sh boot.sh
#
# Time: a few minutes for all of it (c17 is quick; most of it is make
# and the shell).  Programs in the system are linked dynamically, and so
# are by default the programs c17 makes there ("c17 -B static" links
# V86BSD's libc.a); "c17 -G" makes shared libraries.
#
# With -n, stage 3 is left out: the system gets the statically linked
# programs of stage 2 (not stripped), as before.

usage() { echo "usage: sh bootstrap.sh [-k] [-n] [-w workdir] [root]" >&2; exit 2; }

here=$(pwd)
cd "$(dirname "$0")" || exit 2
SRC=$(pwd)
keep=false work=$SRC/obj static=false
while getopts knw: opt; do
	case $opt in
	k) keep=true ;;
	n) static=true ;;
	w) work=$OPTARG ;;
	*) usage ;;
	esac
done
shift $((OPTIND - 1))
[ $# -le 1 ] || usage
root=${1:-$SRC/root}
case $root in /*) ;; *) root=$here/$root ;; esac
case $work in /*) ;; *) work=$here/$work ;; esac
[ "$root" != / ] || { echo "bootstrap: root must not be /" >&2; exit 2; }

# the host's C compiler: CC, or the first of c17 (POSIX.1-2024), c99
# (POSIX.1-2008) and cc on PATH
cc=$CC
if [ -z "$cc" ]; then
	for c in c17 c99 cc; do
		if command -v $c >/dev/null 2>&1; then cc=$c; break; fi
	done
	cc=${cc:-cc}
fi
MAKE=${MAKE:-make}
log=$work/log

say() { printf '%s\n' "== $*"; [ -z "$log" ] || printf '%s\n' "== $*" >> "$log"; }
fail() { echo "bootstrap: $* (see $log)" >&2; exit 1; }

command -v "${cc%% *}" >/dev/null 2>&1 || { echo "bootstrap: no C compiler $cc (set CC)" >&2; exit 1; }
command -v "$MAKE" >/dev/null 2>&1 || { echo "bootstrap: no $MAKE" >&2; exit 1; }
case $(uname -m) in x86_64|amd64) ;; *) echo "bootstrap: x86-64 only (this is $(uname -m))" >&2; exit 1 ;; esac

# A root with file systems mounted in it (chroot.sh while inside, or what a
# killed chroot.sh left) is not removed: rm would empty the host's /dev
# through it.  df -P names the mount point of each directory.
for d in "$root" "$root/dev" "$root/dev/pts" "$root/proc" "$root/sys"; do
	[ -d "$d" ] || continue
	m=$(df -P "$d" 2>/dev/null | awk 'NR == 2 { print $NF }')
	if [ -n "$m" ] && [ "$m" = "$(cd "$d" && pwd -P)" ] && [ "$d" != "$root" ]; then
		echo "bootstrap: $d is a mount point: leave chroot.sh, or umount it, first" >&2
		exit 1
	fi
done
rm -rf "$work" "$root"
mkdir -p "$work" "$root" || exit 1
: > "$log"
start=$(date +%s 2>/dev/null)

# hostmk ARGS: the host's make with the host's compiler (the Makefiles
# need no options beyond POSIX c17's, whatever the compiler)
hostmk() { "$MAKE" CC="$cc" "$@"; }

# copy SRCDIR DEST: a fresh copy of the sources (without objects and
# archives built there by some other compiler)
copy() {
	mkdir -p "$(dirname "$2")" && cp -pR "$SRC/$1" "$2" || fail "copying $1"
	find "$2" \( -name "*.o" -o -name "*.a" \) -type f -exec rm -f {} + || fail "cleaning $1"
}

# ---------------------------------------------------------------- stage 0
S0=$work/stage0
say "stage 0: c17, make, ar, yacc and lex, with the host's $cc"
copy usr.bin "$S0/usr.bin"
copy lib/libxcu "$S0/lib/libxcu"
# the headers of V86BSD's C library, for c17's run-time support library
# (only for that: the host's compiler, which may be a c17 too, must not
# see C17_LIBC)
mkdir -p "$S0/sysroot/lib"
copy include "$S0/sysroot/include"
for u in c17 make ar yacc lex; do
	(cd "$S0/usr.bin/$u" &&
	 hostmk PREFIX="$S0" RTC17="env C17_LIBC=$S0/sysroot ./c17" install) >> "$log" 2>&1 ||
		fail "stage 0: $u"
done

# stage N TOOLS C17DIR ROOT [LIBC]: build the C library and every utility
# with the tools in directory TOOLS (first on PATH), install them into
# ROOT; linked statically.  With LIBC, the C library is not built but
# installed from the build directory LIBC, and the utilities are linked
# dynamically and stripped.
stage() {
	n=$1 tools=$2 c17dir=$3 dest=$4 libcdir=$5
	S=$work/stage$n
	mkdir -p "$dest/usr"
	if [ -z "$libcdir" ]; then
		say "stage $n: the C library, with c17 from $tools"
		copy include "$S/include"
		copy lib/libc "$S/lib/libc"
		libcdir=$S/lib/libc
		c17libc=$dest/usr      # (include/ and lib/: linked statically)
		linkflags= how="statically linked" rtc17=./c17
	else
		say "stage $n: the C library of $libcdir installed"
		# a profile for c17: V86BSD's C library in root, dynamically linked
		c17libc=$work/stage$n.profile
		cat > "$c17libc" <<-EOF
		include $dest/usr/include
		libdir $dest/usr/lib
		crt1 crt1.o
		crti crti.o
		crtn crtn.o
		interp /usr/lib/libc.so
		link dynamic
		EOF
		linkflags=-s how="dynamically linked, stripped" rtc17=c17
	fi
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$dest/usr
		export PATH C17_LIBDIR C17_LIBC
		unset MAKEFLAGS
		cd "$libcdir" &&
		"$tools/make" CCNAME=c17 &&
		"$tools/make" CCNAME=c17 PREFIX=/usr DESTDIR="$dest" install
	) >> "$log" 2>&1 || fail "stage $n: the C library"
	say "stage $n: the utilities, with c17 on V86BSD's C library ($how)"
	copy bin "$S/bin"
	copy sbin "$S/sbin"
	copy usr.bin "$S/usr.bin"
	copy lib/libxcu "$S/lib/libxcu"
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$c17libc
		export PATH C17_LIBDIR C17_LIBC
		unset MAKEFLAGS
		for d in bin sbin usr.bin; do
			(cd "$S/$d" &&
			"$tools/make" CC=c17 LDFLAGS="$linkflags" RTC17="$rtc17" LIBC=v86bsd YACC=yacc LEX=lex \
				PREFIX=/usr DESTDIR="$dest" install) || exit 1
		done
	) >> "$log" 2>&1 || fail "stage $n: the utilities"
}

# ---------------------------------------------------------------- stage 1
R1=$work/stage1/root
stage 1 "$S0/bin" "$S0/lib/c17" "$R1"

# ---------------------------------------------------------------- stage 2
R2=$work/stage2/root
stage 2 "$R1/usr/bin" "$R1/usr/lib/c17" "$R2"

# ---------------------------------------------------------------- check
say "check: stage 1 and stage 2 compared"
differ=0 same=0
(cd "$R2/usr" && find . -type f) | sort > "$work/files"
while IFS= read -r f; do
	a=$R1/usr/$f b=$R2/usr/$f
	[ -f "$a" ] || { echo "only in stage 2: $f" >> "$log"; differ=$((differ + 1)); continue; }
	case $f in
	*.a)
		# archives hold dates: their members are compared
		if [ "$(ar t "$a")" = "$(ar t "$b")" ]; then
			ok=true
			for m in $(ar t "$a"); do
				[ "$(ar p "$a" "$m" | cksum)" = "$(ar p "$b" "$m" | cksum)" ] || { ok=false; break; }
			done
		else ok=false; fi ;;
	*)
		if cmp -s "$a" "$b"; then ok=true; else ok=false; fi ;;
	esac
	if $ok; then same=$((same + 1)); else differ=$((differ + 1)); echo "differs: $f" >> "$log"; fi
done < "$work/files"
say "check: $same files identical, $differ different"
[ "$differ" = 0 ] || echo "bootstrap: stage 1 and stage 2 differ: see $log" >&2

# ---------------------------------------------------------------- stage 3
if $static; then
	say "stage 3 left out: the programs of stage 2 for the system"
	mkdir -p "$root" && cp -pR "$R2/usr" "$root/" || fail "copying stage 2"
else
	stage 3 "$R2/usr/bin" "$R2/usr/lib/c17" "$root" "$work/stage2/lib/libc"
fi

# ---------------------------------------------------------------- kernel
say "kernel: bsd and init, with c17 of stage 2"
copy sys "$work/sys"
copy sbin "$work/sbin"
(
	PATH=$R2/usr/bin:$PATH
	C17_LIBDIR=$R2/usr/lib/c17
	C17_LIBC=$root/usr     # (statically linked)
	export PATH C17_LIBDIR C17_LIBC
	unset MAKEFLAGS
	cd "$work/sys/arch/amd64/compile/GENERIC" &&
	"$R2/usr/bin/make" all &&
	cd "$work/sbin/init" &&
	"$R2/usr/bin/make" C17="c17 -B static" &&
	mkdir -p "$root/usr/sbin" &&
	cp "$work/sys/arch/amd64/compile/GENERIC/bsd" "$root/bsd" &&
	cp "$work/sbin/init/init" "$root/usr/sbin/init"
) >> "$log" 2>&1 || fail "the kernel"

# ---------------------------------------------------------------- system
say "system: /etc, /dev, /proc, /tmp ... and the sources in /usr/src"
(
	cd "$root" || exit 1
	ln -s usr/bin bin && ln -s usr/lib lib && ln -s usr/sbin sbin &&
	mkdir -p etc dev proc sys tmp var/tmp var/spool root home usr/src \
		usr/local/bin usr/local/lib usr/local/include usr/local/share/man usr/lib/locale &&
	chmod 1777 tmp var/tmp && chmod 700 root &&
	cp "$SRC"/etc/* etc/
) || fail "the system directories"
mkdir -p "$root/usr/src"
for d in README.md LICENSE bootstrap.sh chroot.sh mkdisk.sh boot.sh distrib etc share include lib bin sbin usr.bin sys regress ports; do
	cp -pR "$SRC/$d" "$root/usr/src/" || fail "copying the sources"
	# (not all of /usr/src: the ports' sources may be there already)
	find "$root/usr/src/$d" \( -name "*.o" -o -name "*.a" \) -type f -exec rm -f {} +
done
# with the HTML edition of the standard beside the sources: man's pages
if [ -d "$SRC/susv5-html" ] && [ -f "$SRC/usr.bin/man/Makefile" ]; then
	mkdir -p "$root/usr/share" && cp -pR "$SRC/susv5-html" "$root/usr/share/"
fi
# the host's time zone database, for TZ=Area/City (the C library reads
# /usr/share/zoneinfo; without it only POSIX TZ strings such as CET-1CEST
# work); ZONEINFO names another copy
zi=${ZONEINFO:-/usr/share/zoneinfo}
if [ -d "$zi" ]; then
	mkdir -p "$root/usr/share" && cp -pRL "$zi" "$root/usr/share/zoneinfo" 2>/dev/null ||
		say "warning: $zi not copied completely"
	[ -f "$root/usr/share/zoneinfo/UTC" ] && [ ! -e "$root/etc/localtime" ] &&
		{ [ -f /etc/localtime ] && cp -L /etc/localtime "$root/etc/localtime" ||
		  cp "$root/usr/share/zoneinfo/UTC" "$root/etc/localtime"; }
fi
# and its terminfo database, for tput, more, vi and ex (TERMINFO names
# another directory)
for ti in ${TERMINFO:-/usr/share/terminfo /lib/terminfo}; do
	if [ -d "$ti" ]; then
		mkdir -p "$root/usr/share/terminfo" && cp -pRL "$ti/." "$root/usr/share/terminfo" 2>/dev/null ||
			say "warning: $ti not copied completely"
	fi
done
# and its locale sources and charmaps, for localedef (I18N names another
# directory with locales/ and charmaps/); compressed charmaps are
# uncompressed here when the host has gzip (V86BSD's localedef would need
# gzip to read them, which is not a POSIX utility)
i18n=${I18N:-/usr/share/i18n}
if [ -d "$i18n/locales" ] && [ -d "$i18n/charmaps" ]; then
	mkdir -p "$root/usr/share/i18n" && cp -pRL "$i18n/." "$root/usr/share/i18n" 2>/dev/null ||
		say "warning: $i18n not copied completely"
	if command -v gzip >/dev/null 2>&1; then
		find "$root/usr/share/i18n" -name '*.gz' -type f -exec gzip -df {} + ||
			say "warning: the charmaps of $i18n not uncompressed"
	fi
fi
# and its certificate authorities, for curl and other TLS clients
# (ports/curl): /etc/ssl/certs/ca-certificates.crt; CABUNDLE names another
# file (PEM certificates)
for ca in ${CABUNDLE:-/etc/ssl/certs/ca-certificates.crt /etc/pki/tls/certs/ca-bundle.crt \
		/etc/ssl/ca-bundle.pem /etc/ssl/cert.pem}; do
	if [ -f "$ca" ]; then
		mkdir -p "$root/etc/ssl/certs" && cp -L "$ca" "$root/etc/ssl/certs/ca-certificates.crt" ||
			say "warning: $ca not copied"
		break
	fi
done

$keep || [ "$differ" != 0 ] || { rm -rf "$work"; log=; }
end=$(date +%s 2>/dev/null)
say "done: $root ($(du -sk "$root/usr/bin" | awk '{ print $1 }') KiB of programs, $(ls "$root/usr/bin" | wc -l | tr -d ' ') of them)${start:+, $(( (end - start) / 60 )) minutes}"
echo "Enter it:  sh $SRC/chroot.sh $root   (as root: chroot; otherwise a user namespace)"
echo "Or boot it on its own kernel in QEMU:  sh $SRC/mkdisk.sh $root; sh $SRC/boot.sh -k $root/bsd"
[ "$differ" = 0 ]
