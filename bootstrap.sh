#!/bin/sh
# bootstrap.sh - build a Shall system from scratch: the POSIX.1-2024
# utilities and C library of this package, compiled by themselves, in a
# directory that can be entered with chroot (see chroot.sh).
#
# Usage: sh bootstrap.sh [-k] [-w workdir] [root]
#
#   root        the system to make (default: root/ beside this script); it
#               is made afresh
#   -w workdir  where the stages are built (default: work/ beside this script)
#   -k          keep workdir afterwards (default: removed when all went well)
#
# What is needed: a POSIX system with a C compiler (CC, default cc: C11),
# make and ar, on x86-64 Linux.  On Ubuntu: build-essential.  Nothing is
# installed outside workdir and root; root needs no privileges to build.
#
# How it goes (each stage is built from a fresh copy of the sources):
#
#   stage 0  The host's compiler builds five tools of this collection,
#            against the host's own C library: c17 (the C compiler, with
#            its own assembler and link editor), make, ar, yacc and lex.
#
#   stage 1  Those tools build everything: the C library (libc/, with c17
#            and make: libc.a, and libc.so, which is also the dynamic
#            linker), then every utility against it (c17 among them),
#            installed into workdir/stage1/root/usr.  From here on no
#            program of the host compiles anything.
#
#   stage 2  The utilities of stage 1, on Shall's C library, build
#            everything again (with them on PATH first: c17, make, ar,
#            yacc, lex, sh's helpers, cp, ...), installed into root/usr.
#            The grammars of awk, bc and sh are regenerated by Shall's
#            own yacc and lex in both stages.
#
#   check    Stage 1 and stage 2 must be identical, file for file (the
#            members of archives compared one by one): c17 compiled by
#            the host's compiler and c17 compiled by itself produce the
#            same programs.  A difference is reported.
#
#   system   root gets the rest of a small system: /bin and /lib (links to
#            /usr/bin and /usr/lib), /etc (passwd, group, profile, hosts,
#            services, protocols; from system/etc), /tmp, /root, /dev,
#            /proc and /sys (empty: chroot.sh mounts them), and these
#            sources in /usr/src/shall, so that the system can rebuild
#            itself: inside it, "sh /usr/src/shall/bootstrap.sh /tmp/r"
#            runs the same stages with CC=c17.
#
# Then:   sh chroot.sh root   (with or without root privileges)
#
# Time: a few minutes for all of it (c17 is quick; most of it is make
# and the shell).  Programs in the system are linked statically
# (c17 links Shall's libc.a); "c17 -B dynamic" links with
# /usr/lib/libc.so, and "c17 -G" makes shared libraries.

usage() { echo "usage: sh bootstrap.sh [-k] [-w workdir] [root]" >&2; exit 2; }

here=$(pwd)
cd "$(dirname "$0")" || exit 2
SRC=$(pwd)
keep=false work=$SRC/work
while getopts kw: opt; do
	case $opt in
	k) keep=true ;;
	w) work=$OPTARG ;;
	*) usage ;;
	esac
done
shift $((OPTIND - 1))
[ $# -le 1 ] || usage
root=${1:-$SRC/root}
case $root in /*) ;; *) root=$here/$root ;; esac
case $work in /*) ;; *) work=$here/$work ;; esac
[ "$root" != / ] || { echo "bootstrap: root must not be /" >&2; exit 2; }

cc=${CC:-cc}
MAKE=${MAKE:-make}
log=$work/log

say() { printf '%s\n' "== $*"; [ -z "$log" ] || printf '%s\n' "== $*" >> "$log"; }
fail() { echo "bootstrap: $* (see $log)" >&2; exit 1; }

command -v "${cc%% *}" >/dev/null 2>&1 || { echo "bootstrap: no C compiler $cc (set CC)" >&2; exit 1; }
command -v "$MAKE" >/dev/null 2>&1 || { echo "bootstrap: no $MAKE" >&2; exit 1; }
case $(uname -m) in x86_64|amd64) ;; *) echo "bootstrap: x86-64 only (this is $(uname -m))" >&2; exit 1 ;; esac

# A root with file systems mounted in it (chroot.sh while inside, or what a
# killed chroot.sh left) is not removed: rm would empty the host's /dev
# through it.  df -P names the mount point of each directory.
for d in "$root" "$root/dev" "$root/dev/pts" "$root/proc" "$root/sys"; do
	[ -d "$d" ] || continue
	m=$(df -P "$d" 2>/dev/null | awk 'NR == 2 { print $NF }')
	if [ -n "$m" ] && [ "$m" = "$(cd "$d" && pwd -P)" ] && [ "$d" != "$root" ]; then
		echo "bootstrap: $d is a mount point: leave chroot.sh, or umount it, first" >&2
		exit 1
	fi
done
rm -rf "$work" "$root"
mkdir -p "$work" "$root" || exit 1
: > "$log"
start=$(date +%s 2>/dev/null)

# a compiler that does not take -std=c11 and the warning options (c17,
# as POSIX describes it) gets STDFLAGS= with the utilities' Makefiles
t=$work/cc_test
printf 'int main(void) { return 0; }\n' > "$t.c"
if $cc -std=c11 -Wall -Wextra -c -o "$t.o" "$t.c" >/dev/null 2>&1; then stdflags=keep; else stdflags=; fi
rm -f "$t.c" "$t.o"
# hostmk ARGS: the host's make with the host's compiler
hostmk() {
	if [ "$stdflags" = keep ]; then "$MAKE" CC="$cc" "$@"; else "$MAKE" CC="$cc" STDFLAGS= "$@"; fi
}

# the grammars, made afresh by this collection's yacc and lex
GENERATED='awk/awk.tab.c awk/awk.tab.h awk/lex.c bc/bc.tab.c bc/bc.tab.h bc/scan.c
	sh/sh.tab.c sh/sh.tab.h sh/arith.tab.c sh/arith.tab.h sh/arith_scan.c'

# copy SRCDIR DEST: a fresh copy of the sources (without objects and
# archives built there by some other compiler)
copy() {
	mkdir -p "$(dirname "$2")" && cp -pR "$SRC/$1" "$2" || fail "copying $1"
	find "$2" \( -name "*.o" -o -name "*.a" \) -type f -exec rm -f {} + || fail "cleaning $1"
}

# ---------------------------------------------------------------- stage 0
S0=$work/stage0
say "stage 0: c17, make, ar, yacc and lex, with the host's $cc"
copy utilities "$S0/utilities"
# the headers of Shall's C library, for c17's run-time support library
mkdir -p "$S0/sysroot/lib"
copy libc/include "$S0/sysroot/include"
for u in c17 make ar yacc lex; do
	(cd "$S0/utilities/$u" &&
	 C17_LIBC=$S0/sysroot hostmk PREFIX="$S0" install) >> "$log" 2>&1 || fail "stage 0: $u"
done

# stage N TOOLS C17DIR ROOT: build the C library and every utility with
# the tools in directory TOOLS (first on PATH), install them into ROOT
stage() {
	n=$1 tools=$2 c17dir=$3 dest=$4
	S=$work/stage$n
	say "stage $n: the C library, with c17 from $tools"
	copy libc "$S/libc"
	copy utilities "$S/utilities"
	for f in $GENERATED; do rm -f "$S/utilities/$f"; done
	mkdir -p "$dest/usr"
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$dest/usr     # (include/ and lib/: linked statically)
		export PATH C17_LIBDIR C17_LIBC
		unset MAKEFLAGS
		cd "$S/libc" &&
		"$tools/make" CCNAME=c17 &&
		"$tools/make" CCNAME=c17 PREFIX=/usr DESTDIR="$dest" install
	) >> "$log" 2>&1 || fail "stage $n: the C library"
	say "stage $n: the utilities, with c17 on Shall's C library"
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$dest/usr
		export PATH C17_LIBDIR C17_LIBC
		unset MAKEFLAGS
		cd "$S/utilities" &&
		"$tools/make" CC=c17 STDFLAGS= LIBC=shall YACC=yacc LEX=lex PREFIX=/usr DESTDIR="$dest" install
	) >> "$log" 2>&1 || fail "stage $n: the utilities"
}

# ---------------------------------------------------------------- stage 1
R1=$work/stage1/root
stage 1 "$S0/bin" "$S0/lib/c17" "$R1"

# ---------------------------------------------------------------- stage 2
stage 2 "$R1/usr/bin" "$R1/usr/lib/c17" "$root"

# ---------------------------------------------------------------- check
say "check: stage 1 and stage 2 compared"
differ=0 same=0
(cd "$root/usr" && find . -type f) | sort > "$work/files"
while IFS= read -r f; do
	a=$R1/usr/$f b=$root/usr/$f
	[ -f "$a" ] || { echo "only in stage 2: $f" >> "$log"; differ=$((differ + 1)); continue; }
	case $f in
	*.a)
		# archives hold dates: their members are compared
		if [ "$(ar t "$a")" = "$(ar t "$b")" ]; then
			ok=true
			for m in $(ar t "$a"); do
				[ "$(ar p "$a" "$m" | cksum)" = "$(ar p "$b" "$m" | cksum)" ] || { ok=false; break; }
			done
		else ok=false; fi ;;
	*)
		if cmp -s "$a" "$b"; then ok=true; else ok=false; fi ;;
	esac
	if $ok; then same=$((same + 1)); else differ=$((differ + 1)); echo "differs: $f" >> "$log"; fi
done < "$work/files"
say "check: $same files identical, $differ different"
[ "$differ" = 0 ] || echo "bootstrap: stage 1 and stage 2 differ: see $log" >&2

# ---------------------------------------------------------------- system
say "system: /etc, /dev, /proc, /tmp ... and the sources in /usr/src/shall"
(
	cd "$root" || exit 1
	ln -s usr/bin bin && ln -s usr/lib lib &&
	mkdir -p etc dev proc sys tmp var/tmp var/spool root home usr/src &&
	chmod 1777 tmp var/tmp && chmod 700 root &&
	cp "$SRC"/system/etc/* etc/
) || fail "the system directories"
mkdir -p "$root/usr/src/shall"
for d in README.md HOWTO-lua.md LICENSE bootstrap.sh chroot.sh system libc utilities; do
	cp -pR "$SRC/$d" "$root/usr/src/shall/" || fail "copying the sources"
done
find "$root/usr/src/shall" \( -name "*.o" -o -name "*.a" \) -type f -exec rm -f {} +
# with the HTML edition of the standard beside the sources: man's pages
if [ -d "$SRC/susv5-html" ] && [ -f "$SRC/utilities/man/Makefile" ]; then
	mkdir -p "$root/usr/share" && cp -pR "$SRC/susv5-html" "$root/usr/share/"
fi
# the host's time zone database, for TZ=Area/City (the C library reads
# /usr/share/zoneinfo; without it only POSIX TZ strings such as CET-1CEST
# work); ZONEINFO names another copy
zi=${ZONEINFO:-/usr/share/zoneinfo}
if [ -d "$zi" ]; then
	mkdir -p "$root/usr/share" && cp -pRL "$zi" "$root/usr/share/zoneinfo" 2>/dev/null ||
		say "warning: $zi not copied completely"
	[ -f "$root/usr/share/zoneinfo/UTC" ] && [ ! -e "$root/etc/localtime" ] &&
		{ [ -f /etc/localtime ] && cp -L /etc/localtime "$root/etc/localtime" ||
		  cp "$root/usr/share/zoneinfo/UTC" "$root/etc/localtime"; }
fi
# and its terminfo database, for tput, more, vi and ex (TERMINFO names
# another directory)
for ti in ${TERMINFO:-/usr/share/terminfo /lib/terminfo}; do
	if [ -d "$ti" ]; then
		mkdir -p "$root/usr/share/terminfo" && cp -pRL "$ti/." "$root/usr/share/terminfo" 2>/dev/null ||
			say "warning: $ti not copied completely"
	fi
done

$keep || [ "$differ" != 0 ] || { rm -rf "$work"; log=; }
end=$(date +%s 2>/dev/null)
say "done: $root ($(du -sk "$root/usr/bin" | awk '{ print $1 }') KiB of programs, $(ls "$root/usr/bin" | wc -l | tr -d ' ') of them)${start:+, $(( (end - start) / 60 )) minutes}"
echo "Enter it:  sh $SRC/chroot.sh $root   (as root: chroot; otherwise a user namespace)"
[ "$differ" = 0 ]
