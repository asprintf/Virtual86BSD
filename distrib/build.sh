# build.sh - build a Virtual/86 BSD system from scratch: the POSIX.1-2024
# utilities and C library of this package, compiled by themselves, the kernel,
# and a root that can be entered with chroot (chroot.sh) or booted (boot.sh).
# The targets of the Makefile at the top of the tree call this script; so does
# bootstrap.sh (through make).
#
# Usage: sh distrib/build.sh [-n] [-o objdir] [-d destdir] [-c kernconf] command...
#
#   commands (in the order they are meant to be given):
#     newroot       make destdir afresh (removes it first)
#     world         stages 0-3 and init into objdir (buildworld)
#     kernel        the kernel into objdir (buildkernel)
#     installworld  the programs, libraries and headers into destdir, with
#                   the directories of hier(7)
#     distribution  /etc, the sources in /usr/src and the host's data (time
#                   zones, terminfo, locale sources, certificate authorities)
#                   into destdir: a new root only
#     installkernel the kernel as destdir/bsd
#
#   -o objdir     where things are built (default: obj/ beside distrib/)
#   -d destdir    where to install (default: none: the running system, which
#                 is only allowed on V86BSD itself)
#   -c kernconf   the kernel configuration, a directory sys/arch/amd64/
#                 conf/kernconf, run through config(8) (default GENERIC)
#   -n            all programs statically linked (default: those in /bin and
#                 /sbin are, the rest are linked dynamically)
#
# In the environment: CC (the host's compiler: without it gcc, c17, c99 or cc,
# the first there is; gcc builds the whole world in one stage instead of the
# three stages of c17, see below), MAKE, and BUILDER=user@host, the name in the kernel's banner
# (without it that of this machine; to compare two builds, give both the same),
# and ROOTPW, root's password for `distribution' (without it the tree's: root).
#
# What is needed: a POSIX system with a C compiler, make and ar, on x86-64
# Linux (or V86BSD itself).  On Ubuntu: build-essential.  Nothing is installed
# outside objdir and destdir; destdir needs no privileges.
#
# How the world is built (each stage from a fresh copy of the sources):
#
#   stage 0  The host's compiler builds five tools of this collection,
#            against the host's own C library: c17 (the C compiler, with
#            its own assembler and link editor), make, ar, yacc and lex.
#
#   stage 1  Those tools build everything: the C library (lib/libc/, with c17
#            and make: libc.a, and libc.so, which is also the dynamic
#            linker), libcurses (lib/libcurses/: libcurses.a), then every
#            utility against them (c17 among them),
#            installed into objdir/stage1/root/usr (all of them in usr/bin:
#            the programs of these stages run on the host, linked statically,
#            and find one another there).  From here on no program of the host
#            compiles anything.
#
#   stage 2  The utilities of stage 1, on V86BSD's C library, build
#            everything again (with them on PATH first: c17, make, ar,
#            yacc, lex, sh's helpers, cp, ...), installed into
#            objdir/stage2/root/usr.  The grammars of awk, bc and sh are
#            regenerated by V86BSD's own yacc and lex in every stage.
#
#   check    Stage 1 and stage 2 must be identical, file for file (the
#            members of archives compared one by one): c17 compiled by
#            the host's compiler and c17 compiled by itself produce the
#            same programs.  A difference is an error.
#
#   stage 3  The utilities of stage 2 build the utilities once more, for
#            the system, into objdir/world, where they are where hier(7)
#            has them: those of bin/ in /bin and of sbin/ in /sbin, linked
#            statically (they need nothing in /usr), libexec/ (getty) in
#            /usr/libexec statically too, the rest of usr.bin/ in
#            /usr/bin and usr.sbin/ (config) in /usr/sbin, dynamically linked
#            with V86BSD's libc.so (the C
#            library, which is also the dynamic linker, /usr/lib/libc.so);
#            all stripped.  The C library installed is stage 2's (the same
#            as stage 1's).
#
#   init     /sbin/init, the first process, statically linked.
#
#   terminfo /usr/share/misc/terminfo.cdb, libcurses' terminal database,
#            compiled from share/terminfo/terminfo by tic of stage 2.
#
#   kernel   config of stage 2 reads sys/arch/amd64/conf/GENERIC (the file
#            named by -c) and writes the compile directory: Makefile, ioconf.c
#            and the rest; then c17 of stage 2 builds the kernel (sys/: c17
#            compiles its C, assembles its assembly and links it): bsd.  The
#            banner of the kernel names who built it.
#
#   install  root gets /bin /sbin /usr ... as above, /etc from etc/, the
#            sources in /usr/src, so that the system can rebuild itself:
#            inside it, "cd /usr/src && make buildworld buildkernel" runs the
#            same stages with CC=c17.
#
# With gcc as the host's compiler there is no stage 2 of its own and no check: stage 1
# is built by gcc (libc-cc, against the headers and library of the stage), stage 2
# is stage 1 (a link), and stage 3, init and the kernel (make gnu) are gcc's too.
# $obj/worldcc keeps which compiler built the world, for buildkernel.
#
# Time: a few minutes for all of it (c17 is quick; most of it is make
# and the shell).

usage() {
	echo "usage: sh build.sh [-n] [-o objdir] [-d destdir] [-c kernconf] newroot|world|kernel|installworld|distribution|installkernel..." >&2
	exit 2
}

here=$(pwd)
cd "$(dirname "$0")/.." || exit 2
SRC=$(pwd)
obj= dest= kernconf=GENERIC static=false
while getopts no:d:c: opt; do
	case $opt in
	n) static=true ;;
	o) obj=$OPTARG ;;
	d) dest=$OPTARG ;;
	c) kernconf=$OPTARG ;;
	*) usage ;;
	esac
done
shift $((OPTIND - 1))
[ $# -ge 1 ] || usage
[ -n "$obj" ] || obj=$SRC/obj
[ -n "$kernconf" ] || kernconf=GENERIC
case $obj in /*) ;; *) obj=$here/$obj ;; esac
case $dest in ""|/) dest= ;; /*) ;; *) dest=$here/$dest ;; esac
dest=${dest%/}	# (empty: the running system; "$dest/usr" is then /usr)

# What make exports to a recipe must not reach the makes below, where
# DESTDIR, PREFIX and BINDIR mean something else (they are given there
# explicitly where needed): the options of this script and the macros of the
# Makefile are not passed on
unset MAKEFLAGS MFLAGS DESTDIR OBJDIR KERNCONF HOSTCC BUILDFLAGS BINDIR PREFIX \
	RELROOT IMGROOT IMAGE IMGSIZE BOOTFLAGS
[ -n "$BUILDER" ] && export BUILDER || unset BUILDER

# the host's C compiler: CC, or the first of gcc, c17 (POSIX.1-2024), c99
# (POSIX.1-2008) and cc on PATH
cc=$CC
if [ -z "$cc" ]; then
	for c in gcc c17 c99 cc; do
		if command -v $c >/dev/null 2>&1; then cc=$c; break; fi
	done
	cc=${cc:-cc}
fi
MAKE=${MAKE:-make}
log=$obj/log
W=$obj/world
R1=$obj/stage1/root
R2=$obj/stage2/root

# who builds the world: gcc, when that is the host's compiler (then there is
# no stage 2: its place is stage 1, which gcc built), else c17 itself in
# three stages.  $obj/worldcc keeps it for the kernel and the image.
cc1=${cc%% *}
case ${cc1##*/} in gcc*) detected=gcc ;; *) detected=c17 ;; esac
worldcc=$detected
[ ! -f "$obj/worldcc" ] || read worldcc < "$obj/worldcc"
setworld() {
	hostworld=false wdesc="c17 of stage 2"
	if [ "$worldcc" = gcc ]; then hostworld=true wdesc=gcc; fi
}
setworld
WCFLAGS=${WCFLAGS:--std=c17 -D_DEFAULT_SOURCE= -O2 -pipe -fPIE -fno-stack-protector -fcf-protection=none -Wall -Wextra -Wno-unused-parameter -Wno-missing-field-initializers}

say() { printf '%s\n' "== $*"; [ ! -d "$obj" ] || printf '%s\n' "== $*" >> "$log"; }
fail() { echo "build: $* (see $log)" >&2; exit 1; }

# hostmk ARGS: the host's make with the host's compiler (the Makefiles
# need no options beyond POSIX c17's, whatever the compiler)
hostmk() { "$MAKE" CC="$cc" "$@"; }

# copy SRCDIR DEST: a fresh copy of the sources (without objects and
# archives built there by some other compiler)
copy() {
	# -L: include/sys/*.h are links to sys/sys, and the copy has no sys/sys beside it
	mkdir -p "$(dirname "$2")" && cp -pRL "$SRC/$1" "$2" || fail "copying $1"
	find "$2" \( -name "*.o" -o -name "*.a" \) -type f -exec rm -f {} + || fail "cleaning $1"
}

# an install into the running system only on V86BSD itself, and a
# distribution only into a new root
guard_dest() {
	if [ -z "$dest" ]; then
		[ "$(uname -s)" = V86BSD ] || {
			echo "build: no DESTDIR: refusing to install into the / of this $(uname -s) host" >&2
			exit 1
		}
		[ "$1" != new ] || {
			echo "build: distribution (/etc, ...) is for a new root: give DESTDIR" >&2
			exit 1
		}
	fi
}

# ---------------------------------------------------------------- newroot
do_newroot() {
	[ -n "$dest" ] || { echo "build: newroot: give DESTDIR (a directory to make afresh)" >&2; exit 2; }
	# not the sources, nor what holds them, nor the current directory, nor
	# home: compared by their real names (no ".", no links)
	if [ -d "$dest" ]; then dest=$(cd "$dest" && pwd -P) || exit 1; fi
	srcp=$(cd "$SRC" && pwd -P) herep=$(cd "$here" && pwd -P)
	homep=$(cd "$HOME" 2>/dev/null && pwd -P)
	case $dest in /*) ;; *) echo "build: newroot: $dest: not a path" >&2; exit 1 ;; esac
	[ "$dest" != / ] || { echo "build: root must not be /" >&2; exit 1; }
	case $srcp/ in "$dest"/*) echo "build: $dest holds the sources: not removed" >&2; exit 1 ;; esac
	case $herep/ in "$dest"/*) echo "build: $dest holds the current directory: not removed" >&2; exit 1 ;; esac
	[ "$dest" != "$homep" ] || { echo "build: $dest is your home: not removed" >&2; exit 1; }
	# A root with file systems mounted in it (chroot.sh while inside, or what
	# a killed chroot.sh left) is not removed: rm would empty the host's /dev
	# through it.  df -P names the mount point of each directory.
	for d in "$dest" "$dest/dev" "$dest/dev/pts" "$dest/proc" "$dest/sys"; do
		[ -d "$d" ] || continue
		m=$(df -P "$d" 2>/dev/null | awk 'NR == 2 { print $NF }')
		if [ -n "$m" ] && [ "$m" = "$(cd "$d" && pwd -P)" ] && [ "$d" != "$dest" ]; then
			echo "build: $d is a mount point: leave chroot.sh, or umount it, first" >&2
			exit 1
		fi
	done
	rm -rf "$dest" && mkdir -p "$dest" || exit 1
}

# ---------------------------------------------------------------- world
# stage N TOOLS C17DIR ROOT [LIBC]: build the C library and every utility
# with the tools in directory TOOLS (first on PATH), install them into
# ROOT.  Without LIBC (stages 1 and 2) everything is linked statically and
# installed under ROOT/usr.  With LIBC (stage 3), the C library is not
# built but installed from the build directory LIBC, and the utilities are
# stripped: those of bin/ and sbin/ linked statically, the rest dynamically.
# abi_headers INCLUDEDIR ABI: what the kernel's sys/ gives the C library's
# include/: reboot.h always (a link to sys/sys in the tree, a file here),
# syscall.h, V86BSD's own numbers, only for the native ABI
abi_headers() {
	rm -f "$1/sys/reboot.h" "$1/sys/syscall.h"
	cp "$SRC/sys/sys/reboot.h" "$1/sys/reboot.h" || fail "reboot.h"
	if [ "$2" = native ]; then
		cp "$SRC/sys/sys/syscall.h" "$1/sys/syscall.h" || fail "syscall.h"
	fi
}

# stage N TOOLS C17DIR TO [LIBCDIR]: ABI is the system call ABI of the
# library and the programs: linux in stages 1 and 2 (they run on the host's
# Linux, or as Linux programs on V86BSD), native (V86BSD's own numbers and
# brand) in stage 3, the world
stage() {
	n=$1 tools=$2 c17dir=$3 to=$4 libcdir=$5 forsystem=$5
	S=$obj/stage$n
	abi=linux
	[ -z "$forsystem" ] || abi=native
	mkdir -p "$to/usr"
	# the compiler of the stage: c17 (the tools') or gcc through libc-cc, which
	# links with this stage's library (LIBC_LIB, LIBC_INCLUDE; a dynamic
	# program asks for /usr/lib/libc.so)
	ccname=c17 wcc=c17
	if $hostworld; then
		ccname=gcc wcc="sh $SRC/lib/libc/tools/libc-cc gcc $WCFLAGS"
		LIBC_INCLUDE=$to/usr/include LIBC_LIB=$to/usr/lib LIBC_INTERP=/usr/lib/libc.so
		export LIBC_INCLUDE LIBC_LIB LIBC_INTERP
	fi
	if [ -z "$libcdir" ]; then
		say "stage $n: the C library, with $ccname${tools:+ (tools from $tools)}"
		copy include "$S/include"
		abi_headers "$S/include" $abi
		copy lib/libc "$S/lib/libc"
		libcdir=$S/lib/libc
		c17libc=$to/usr      # (include/ and lib/: linked statically)
		how="statically linked" rtc17=./c17
	else
		say "stage $n: the C library, native ABI (V86BSD's own system call numbers)"
		copy include "$S/include"
		abi_headers "$S/include" $abi
		copy lib/libc "$S/lib/libc"
		libcdir=$S/lib/libc
		# a profile for c17: V86BSD's C library in root, dynamically linked
		c17libc=$obj/stage$n.profile
		cat > "$c17libc" <<-EOF
		include $to/usr/include
		libdir $to/usr/lib
		crt1 crt1.o
		crti crti.o
		crtn crtn.o
		interp /usr/lib/libc.so
		link dynamic
		EOF
		how="bin and sbin statically linked, the rest dynamically, stripped" rtc17=c17
	fi
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$to/usr
		export PATH C17_LIBDIR C17_LIBC
		cd "$libcdir" &&
		"$tools/make" CCNAME=$ccname TARGET_ABI=$abi SYSCALL_H="$SRC/sys/sys/syscall.h" &&
		"$tools/make" CCNAME=$ccname TARGET_ABI=$abi SYSCALL_H="$SRC/sys/sys/syscall.h" PREFIX=/usr DESTDIR="$to" install
	) >> "$log" 2>&1 || fail "stage $n: the C library"
	say "stage $n: libcurses (X/Open Curses, terminfo, termcap)"
	copy lib/libcurses "$S/lib/libcurses"
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$to/usr
		export PATH C17_LIBDIR C17_LIBC
		cd "$S/lib/libcurses" &&
		LIBC_LINK=static "$tools/make" CC="$wcc" PREFIX=/usr DESTDIR="$to" install
	) >> "$log" 2>&1 || fail "stage $n: libcurses"
	say "stage $n: the utilities, with $ccname on V86BSD's C library ($how)"
	copy bin "$S/bin"
	copy sbin "$S/sbin"
	# fsck_ffs builds the driver'"'"'s bit map code from ../../sys/ufs/ffs
	mkdir -p "$S/sys/ufs/ffs" && cp -p "$SRC/sys/ufs/ffs/ffs_subr.c" "$SRC/sys/ufs/ffs/ffs_tables.c" \
		"$S/sys/ufs/ffs/" || fail "copying sys/ufs/ffs"
	copy libexec "$S/libexec"
	copy usr.bin "$S/usr.bin"
	copy usr.sbin "$S/usr.sbin"
	copy lib/libxcu "$S/lib/libxcu"
	(
		PATH=$tools:$PATH
		C17_LIBDIR=$c17dir
		C17_LIBC=$c17libc
		export PATH C17_LIBDIR C17_LIBC
		for d in bin sbin libexec usr.bin usr.sbin; do
			if [ -z "$forsystem" ]; then
				bindir=BINDIR=/usr/bin lf= lk=static	# (all together, for the next stage)
			elif $static || { [ "$d" != usr.bin ] && [ "$d" != usr.sbin ]; }; then
				bindir= lf="-B static -s" lk=static	# (BINDIR: /bin, /sbin, /usr/bin, /usr/sbin)
			else
				bindir= lf=-s lk=dynamic
			fi
			$hostworld && lf=${lf#-B static }	# (gcc: LIBC_LINK says it)
			(cd "$S/$d" &&
			LIBC_LINK=$lk "$tools/make" CC="$wcc" LDFLAGS="$lf" RTC17="$rtc17" LIBC=v86bsd YACC=yacc LEX=lex $bindir \
				PREFIX=/usr DESTDIR="$to" install) || exit 1
		done
	) >> "$log" 2>&1 || fail "stage $n: the utilities"
}

do_world() {
	command -v "${cc%% *}" >/dev/null 2>&1 || { echo "build: no C compiler $cc (set CC)" >&2; exit 1; }
	command -v "$MAKE" >/dev/null 2>&1 || { echo "build: no $MAKE" >&2; exit 1; }
	case $(uname -m) in x86_64|amd64) ;; *) echo "build: x86-64 only (this is $(uname -m))" >&2; exit 1 ;; esac
	rm -rf "$obj/stage0" "$obj/stage1" "$obj/stage2" "$obj/stage3" "$obj/world" "$obj"/stage*.profile
	mkdir -p "$obj" || exit 1
	: > "$log"
	worldcc=$detected
	setworld
	echo "$worldcc" > "$obj/worldcc"
	start=$(date +%s 2>/dev/null)

	# ------------------------------------------------------------ stage 0
	S0=$obj/stage0
	say "stage 0: c17, make, ar, yacc and lex, with the host's $cc"
	copy usr.bin "$S0/usr.bin"
	copy usr.sbin "$S0/usr.sbin"
	copy lib/libxcu "$S0/lib/libxcu"
	# the headers of V86BSD's C library, for c17's run-time support library
	# (only for that: the host's compiler, which may be a c17 too, must not
	# see C17_LIBC)
	mkdir -p "$S0/sysroot/lib"
	copy include "$S0/sysroot/include"
	for u in c17 make ar yacc lex; do
		(cd "$S0/usr.bin/$u" &&
		 hostmk PREFIX="$S0" RTC17="env C17_LIBC=$S0/sysroot ./c17" install) >> "$log" 2>&1 ||
			fail "stage 0: $u"
	done
	# config(8) too, to see that the host's compiler builds it; the kernel
	# is configured by the config of stage 2
	(cd "$S0/usr.sbin/config" && hostmk PREFIX="$S0" install) >> "$log" 2>&1 ||
		fail "stage 0: config"

	# ------------------------------------------------------------ stages 1, 2
	if $hostworld; then
		# gcc builds the world once, with no c17 to prove (stage 2 is stage 1)
		stage 1 "$S0/bin" "$S0/lib/c17" "$R1"
		ln -s stage1 "$obj/stage2" || fail "stage 2"
	else
		stage 1 "$S0/bin" "$S0/lib/c17" "$R1"
		stage 2 "$R1/usr/bin" "$R1/usr/lib/c17" "$R2"

		# ------------------------------------------------------------ check
		say "check: stage 1 and stage 2 compared"
		differ=0 same=0
		(cd "$R2/usr" && find . -type f) | sort > "$obj/files"
		while IFS= read -r f; do
			a=$R1/usr/$f b=$R2/usr/$f
			[ -f "$a" ] || { echo "only in stage 2: $f" >> "$log"; differ=$((differ + 1)); continue; }
			case $f in
			*.a)
				# archives hold dates: their members are compared
				if [ "$(ar t "$a")" = "$(ar t "$b")" ]; then
					ok=true
					for m in $(ar t "$a"); do
						[ "$(ar p "$a" "$m" | cksum)" = "$(ar p "$b" "$m" | cksum)" ] || { ok=false; break; }
					done
				else ok=false; fi ;;
			*)
				if cmp -s "$a" "$b"; then ok=true; else ok=false; fi ;;
			esac
			if $ok; then same=$((same + 1)); else differ=$((differ + 1)); echo "differs: $f" >> "$log"; fi
		done < "$obj/files"
		say "check: $same files identical, $differ different"
		[ "$differ" = 0 ] || fail "stage 1 and stage 2 differ"
	fi

	# ------------------------------------------------------------ stage 3
	stage 3 "$R2/usr/bin" "$R2/usr/lib/c17" "$W" native

	# ------------------------------------------------------------ init
	say "init: /sbin/init, with $wdesc (statically linked)"
	(
		PATH=$R2/usr/bin:$PATH
		C17_LIBDIR=$R2/usr/lib/c17
		C17_LIBC=$W/usr     # (statically linked)
		export PATH C17_LIBDIR C17_LIBC
		initcc="c17 -B static"
		if $hostworld; then
			LIBC_INCLUDE=$W/usr/include LIBC_LIB=$W/usr/lib LIBC_LINK=static
			export LIBC_INCLUDE LIBC_LIB LIBC_LINK
			initcc="sh $SRC/lib/libc/tools/libc-cc gcc $WCFLAGS"
		fi
		cd "$obj/stage3/sbin/init" &&
		"$R2/usr/bin/make" C17="$initcc" DESTDIR="$W" install
	) >> "$log" 2>&1 || fail "init"

	# ------------------------------------------------------------ terminfo
	# the terminal database of libcurses, compiled by tic of stage 2 (which
	# runs here); its source beside it
	say "terminfo: /usr/share/misc/terminfo.cdb, with tic of stage 2"
	mkdir -p "$W/usr/share/misc" &&
	cp "$SRC/share/terminfo/terminfo" "$W/usr/share/misc/terminfo" &&
	"$R2/usr/bin/tic" -ax -o "$W/usr/share/misc/terminfo.cdb" "$W/usr/share/misc/terminfo" >> "$log" 2>&1 ||
		fail "terminfo"

	end=$(date +%s 2>/dev/null)
	say "world: $W ($(ls "$W/bin" | wc -l | tr -d ' ') programs in /bin, $(ls "$W/sbin" | wc -l | tr -d ' ') in /sbin, $(ls "$W/usr/bin" | wc -l | tr -d ' ') in /usr/bin)${start:+, $(( (end - start) / 60 )) minutes}"
}

# ---------------------------------------------------------------- kernel
do_kernel() {
	[ -f "$SRC/sys/arch/amd64/conf/$kernconf" ] ||
		{ echo "build: no kernel configuration $kernconf (sys/arch/amd64/conf/$kernconf)" >&2; exit 1; }
	[ -x "$R2/usr/bin/c17" ] && [ -d "$W/usr/lib" ] ||
		{ echo "build: no world in $obj: make buildworld first" >&2; exit 1; }
	[ -d "$obj" ] || mkdir -p "$obj" || exit 1
	rm -rf "$obj/sys"
	# mkimage runs here, in the build: it is built by the host's compiler (its
	# own C library and ABI), not by c17 of the world, whose library is native
	hostcc=$(command -v "${cc%% *}") || { echo "build: no C compiler $cc (set CC)" >&2; exit 1; }
	case $cc in *\ *) hostcc="$hostcc ${cc#* }" ;; esac
	say "kernel: bsd ($kernconf), with $wdesc"
	copy sys "$obj/sys"
	# (what a build in the tree left in the compile directories is not kept)
	rm -rf "$obj/sys/arch/amd64/compile/$kernconf"
	(
		PATH=$R2/usr/bin:$PATH
		C17_LIBDIR=$R2/usr/lib/c17
		C17_LIBC=$W/usr     # (statically linked)
		export PATH C17_LIBDIR C17_LIBC
		# config(8), run in the directory of the configurations as
		# OpenBSD's is: the compile directory is ../compile/$kernconf
		cd "$obj/sys/arch/amd64/conf" &&
		"$R2/usr/bin/config" "$kernconf" &&
		cd "../compile/$kernconf" &&
		if $hostworld; then
			"$R2/usr/bin/make" KINC="$W/usr/include" gnu
		else
			"$R2/usr/bin/make" HOSTCC="$hostcc" all
		fi
	) >> "$log" 2>&1 || fail "the kernel"
	say "kernel: $obj/sys/arch/amd64/compile/$kernconf/bsd"
}

# ---------------------------------------------------------------- install
# mkd [-m MODE] DIR...: the directories under dest, with a mode only where
# they are new
mkd() {
	mode=
	if [ "$1" = -m ]; then mode=$2; shift 2; fi
	for d in "$@"; do
		if [ ! -d "$dest/$d" ]; then
			mkdir -p "$dest/$d" || exit 1
			[ -z "$mode" ] || chmod "$mode" "$dest/$d" || exit 1
		fi
	done
}

# the directories of hier(7), in V86BSD's form: /bsd, /bin and /sbin (real
# directories), /dev, /proc (the kernel mounts file systems there), /etc,
# /home, /mnt, /root, /tmp, /usr/{bin,sbin,lib,libexec,include,share,local,src},
# /var/{log,run,db,tmp,spool,cron}; no /boot (the kernel is /bsd) and no /sys
hier() {
	mkd bin sbin dev proc etc home mnt \
		usr/bin usr/sbin usr/lib usr/libexec usr/include usr/share usr/src \
		usr/local/bin usr/local/lib usr/local/include usr/local/share/man usr/lib/locale \
		var/log var/run var/db var/spool var/cron
	mkd -m 1777 tmp var/tmp
	mkd -m 700 root
}

do_installworld() {
	guard_dest
	[ -d "$W/usr" ] || { echo "build: no world in $obj: make buildworld first" >&2; exit 1; }
	say "installworld: /bin, /sbin and /usr into ${dest:-/}"
	mkdir -p "$dest/" 2>/dev/null
	hier
	cp -pR "$W/." "$dest/" || fail "installing the world"
}

do_installkernel() {
	guard_dest
	k=$obj/sys/arch/amd64/compile/$kernconf/bsd
	[ -f "$k" ] || { echo "build: no $k: make buildkernel first" >&2; exit 1; }
	say "installkernel: ${dest:-}/bsd"
	cp "$k" "$dest/bsd" || fail "installing the kernel"
}

do_distribution() {
	guard_dest new
	say "distribution: /etc, the sources in /usr/src and the host's data into $dest"
	hier
	cp -pR "$SRC"/etc/* "$dest/etc/" || fail "copying etc/"
	chmod 755 "$dest"/etc/rc.d/* && chmod 644 "$dest/etc/rc.d/rc.subr" || fail "modes of etc/rc.d"
	chmod 600 "$dest/etc/master.passwd"	# (the hashes: git keeps no modes but the x bit)
	# ROOTPW=word: root's password is that (the tree's is `root'), with a
	# salt of its own; the word goes to openssl by its input, not its arguments
	if [ -n "$ROOTPW" ]; then
		command -v openssl >/dev/null 2>&1 || fail "ROOTPW needs openssl on the host (openssl passwd -6)"
		h=$(printf '%s\n' "$ROOTPW" | openssl passwd -6 -stdin) && [ -n "$h" ] || fail "hashing ROOTPW"
		pw=$dest/etc/master.passwd
		( umask 077; H=$h awk 'BEGIN { FS = OFS = ":" } $1 == "root" { $2 = ENVIRON["H"] } { print }' "$pw" > "$pw.new" ) &&
			mv "$pw.new" "$pw" && chmod 600 "$pw" || fail "setting root's password"
		unset h
	fi
	mkdir -p "$dest/usr/src"
	for d in README.md LICENSE Makefile bootstrap.sh chroot.sh mkdisk.sh boot.sh distrib etc share include lib bin sbin libexec usr.bin usr.sbin sys regress ports; do
		cp -pR "$SRC/$d" "$dest/usr/src/" || fail "copying the sources"
		# (not all of /usr/src: the ports' sources may be there already)
		find "$dest/usr/src/$d" \( -name "*.o" -o -name "*.a" \) -type f -exec rm -f {} +
	done
	# with the HTML edition of the standard beside the sources: man's pages
	if [ -d "$SRC/susv5-html" ] && [ -f "$SRC/usr.bin/man/Makefile" ]; then
		mkdir -p "$dest/usr/share" && cp -pR "$SRC/susv5-html" "$dest/usr/share/"
	fi
	# the host's time zone database, for TZ=Area/City (the C library reads
	# /usr/share/zoneinfo; without it only POSIX TZ strings such as CET-1CEST
	# work); ZONEINFO names another copy
	zi=${ZONEINFO:-/usr/share/zoneinfo}
	if [ -d "$zi" ]; then
		mkdir -p "$dest/usr/share" && cp -pRL "$zi" "$dest/usr/share/zoneinfo" 2>/dev/null ||
			say "warning: $zi not copied completely"
		[ -f "$dest/usr/share/zoneinfo/UTC" ] && [ ! -e "$dest/etc/localtime" ] &&
			{ [ -f /etc/localtime ] && cp -L /etc/localtime "$dest/etc/localtime" ||
			  cp "$dest/usr/share/zoneinfo/UTC" "$dest/etc/localtime"; }
	fi
	# and its terminfo database, for tput, more, vi and ex (TERMINFO names
	# another directory)
	for ti in ${TERMINFO:-/usr/share/terminfo /lib/terminfo}; do
		if [ -d "$ti" ]; then
			mkdir -p "$dest/usr/share/terminfo" && cp -pRL "$ti/." "$dest/usr/share/terminfo" 2>/dev/null ||
				say "warning: $ti not copied completely"
		fi
	done
	# and its locale sources and charmaps, for localedef (I18N names another
	# directory with locales/ and charmaps/); compressed charmaps are
	# uncompressed here when the host has gzip (V86BSD's localedef would need
	# gzip to read them, which is not a POSIX utility)
	i18n=${I18N:-/usr/share/i18n}
	if [ -d "$i18n/locales" ] && [ -d "$i18n/charmaps" ]; then
		mkdir -p "$dest/usr/share/i18n" && cp -pRL "$i18n/." "$dest/usr/share/i18n" 2>/dev/null ||
			say "warning: $i18n not copied completely"
		if command -v gzip >/dev/null 2>&1; then
			find "$dest/usr/share/i18n" -name '*.gz' -type f -exec gzip -df {} + ||
				say "warning: the charmaps of $i18n not uncompressed"
		fi
	fi
	# and its certificate authorities, for curl and other TLS clients
	# (ports/curl): /etc/ssl/certs/ca-certificates.crt; CABUNDLE names another
	# file (PEM certificates)
	for ca in ${CABUNDLE:-/etc/ssl/certs/ca-certificates.crt /etc/pki/tls/certs/ca-bundle.crt \
			/etc/ssl/ca-bundle.pem /etc/ssl/cert.pem}; do
		if [ -f "$ca" ]; then
			mkdir -p "$dest/etc/ssl/certs" && cp -L "$ca" "$dest/etc/ssl/certs/ca-certificates.crt" ||
				say "warning: $ca not copied"
			break
		fi
	done
}

for cmd in "$@"; do
	case $cmd in newroot|world|kernel|installworld|distribution|installkernel) ;; *) usage ;; esac
done
for cmd in "$@"; do
	"do_$cmd" || exit 1
done
