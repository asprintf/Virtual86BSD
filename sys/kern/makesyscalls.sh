# makesyscalls.sh - write the system call files from a syscalls.master.
#
# Usage: sh makesyscalls.sh [sysdir [conf...]]
#   sysdir  the sys/ directory (default .)
#   conf    configuration files, from sysdir (default: kern/syscalls.conf, and
#           compat/linux/syscalls.conf when there is one).  Each is a shell
#           fragment that sets
#             master       the table (lines "number STD { prototype }")
#             sysent       the .c file written: the table, by number
#             tabname      the name of that table
#             syscallh     the header written: a macro per call, its number
#             argsh        the header written: the prototypes
#             macroprefix  SYS_ or LINUX_SYS_
#             protoprefix  only functions with this prefix get a prototype
#             includes     headers the .c file includes
#             maxname      the macro for the size of the table
#
# Only POSIX sh and awk, and the same bytes on any host: the generated files
# are in the tree, and a rebuild must not change them.
S=${1:-.}
[ $# -gt 0 ] && shift
if [ $# -eq 0 ]; then
	set -- kern/syscalls.conf
	[ -f "$S/compat/linux/syscalls.conf" ] && set -- "$@" compat/linux/syscalls.conf
fi

for c in "$@"; do
	master= sysent= tabname= syscallh= argsh= macroprefix= protoprefix= includes= maxname=
	. "$S/$c"
	LC_ALL=C awk -v master="$master" -v sysent="$sysent" -v tabname="$tabname" \
	    -v syscallh="$syscallh" -v argsh="$argsh" -v mp="$macroprefix" -v S="$S" \
	    -v pp="$protoprefix" -v includes="$includes" -v maxname="$maxname" '
	function guard(f,   g) { g = f
		gsub(/[^A-Za-z0-9]/, "_", g); return "_" toupper(g) "_" }
	/^;/ || /^[ \t]*$/ { next }
	$1 ~ /^[0-9]+$/ && $2 == "STD" {
		p = $0; sub(/^[^{]*\{[ \t]*/, "", p); sub(/[ \t]*\}[ \t]*$/, "", p)
		f = p; sub(/^[^ ]+[ \t]+/, "", f); sub(/\(.*/, "", f)
		n = $1 + 0
		if (n in fn) { print "makesyscalls: " master ": number " n " twice" > "/dev/stderr"; bad = 1 }
		if (f in seen) { print "makesyscalls: " master ": " f " twice" > "/dev/stderr"; bad = 1 }
		seen[f] = 1; fn[n] = f; proto[n] = p
		if (n > max) max = n
		next
	}
	{ print "makesyscalls: " master ": bad line: " $0 > "/dev/stderr"; bad = 1 }
	END {
		if (bad) exit 1
		max++
		print "/* " sysent ": generated by kern/makesyscalls.sh from " master ": do not edit. */" > (S "/" sysent)
		ni = split(includes, inc, " ")
		print "#include <sys/param.h>\n#include <sys/systm.h>\n#include <sys/proc.h>" > (S "/" sysent)
		printf "#include <%s>\n", syscallh > (S "/" sysent)
		for (i = 1; i <= ni; i++) print "#include " inc[i] > (S "/" sysent)
		print "\n#define S(f) { (sy_call_t)(f) }\n" > (S "/" sysent)
		print "const struct sysent " tabname "[" maxname "] = {" > (S "/" sysent)
		g = guard(syscallh)
		print "/* " syscallh ": generated by kern/makesyscalls.sh from " master ": do not edit. */" > (S "/" syscallh)
		print "#ifndef " g "\n#define " g "\n" > (S "/" syscallh)
		g2 = guard(argsh)
		print "/* " argsh ": generated by kern/makesyscalls.sh from " master ": do not edit. */" > (S "/" argsh)
		print "#ifndef " g2 "\n#define " g2 "\n#include <sys/systm.h>" > (S "/" argsh)
		if (pp == "sys_") print "long sys_nosys(void);" > (S "/" argsh)
		for (i = 0; i < max; i++) {
			if (i in fn) {
				f = fn[i]; m = f; sub(/^linux_sys_/, "", m); sub(/^sys_/, "", m)
				printf "\tS(%s),\t/* %d = %s */\n", f, i, m > (S "/" sysent)
				printf "#define\t%s%s\t%d\n", mp, m, i > (S "/" syscallh)
				if (index(f, pp) == 1) print proto[i] > (S "/" argsh)
			} else
				printf "\tS(sys_nosys),\t/* %d */\n", i > (S "/" sysent)
		}
		print "};" > (S "/" sysent)
		printf "\n#define\t%s\t%d\n", maxname, max > (S "/" syscallh)
		print "\n#endif" > (S "/" syscallh)
		print "#endif" > (S "/" argsh)
	}' "$S/$master" || exit 1
	# the licence header, as on every source file (the files are in the tree)
	sh "$S/../distrib/copyright.sh" -b "$S/$sysent" "$S/$syscallh" "$S/$argsh" || exit 1
done
