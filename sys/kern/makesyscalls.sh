#!/bin/sh
# makesyscalls.sh - write sys/sys/syscallargs.h: the prototypes of every
# "long sys_NAME(...)" defined in the kernel sources.
#
# Usage: sh makesyscalls.sh [sysdir]     (sysdir: the sys/ directory, default .)
S=${1:-.}
{
  echo '/* generated by kern/makesyscalls.sh: do not edit */'
  echo '#ifndef _SYS_SYSCALLARGS_H_'
  echo '#define _SYS_SYSCALLARGS_H_'
  echo '#include <sys/systm.h>'
  find "$S" -name '*.c' | LC_ALL=C sort |
    xargs cat |
    awk '/^long sys_[a-z0-9_]*\([^)]*\) \{/ { i = index($0, ")"); print substr($0, 1, i) ";" }'
  echo '#endif'
} > "$S/sys/syscallargs.h"
