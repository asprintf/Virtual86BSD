#!/bin/sh
# mktwoopi.sh - write src/math/twoopi.h: the bits of 2/pi after the
# binary point, for the Payne-Hanek argument reduction of sinl() etc.
# (long double arguments up to 2^16384 need about 16600 bits).
# Computed with bc: pi = 16 atan(1/5) - 4 atan(1/239) (Machin).
cd "$(dirname "$0")/.." || exit 1
{
	echo '/* Generated by tools/mktwoopi.sh; do not edit.  2/pi = 0.TWOOPI[0] TWOOPI[1] ... */'
	echo 'static const uint32_t __twoopi[] = {'
	echo 'scale=5100; p=16*a(1/5)-4*a(1/239); obase=16; 2/p' | BC_LINE_LENGTH=0 bc -l |
	awk '{ s = $0; sub(/^\./, "", s); n = int(length(s) / 8); if (n > 524) n = 524
	       for (i = 0; i < n; i++) printf "%s0x%s,%s", (i % 6 ? " " : "\t"), substr(s, 8 * i + 1, 8), (i % 6 == 5 || i == n - 1 ? "\n" : "") }'
	echo '};'
} > src/math/twoopi.h
