/* sigignore(): SUSv2, SUSv3, SUSv4, removed in POSIX.1-2024 (sigaction()). */
#define _DEFAULT_SOURCE
#include <signal.h>
#include <string.h>

/* EINVAL for a signal that cannot be ignored (SIGKILL, SIGSTOP) comes
 * from sigaction() */
int sigignore(int sig)
{
	struct sigaction sa;
	memset(&sa, 0, sizeof sa);
	sa.sa_handler = SIG_IGN;
	return sigaction(sig, &sa, 0);
}
