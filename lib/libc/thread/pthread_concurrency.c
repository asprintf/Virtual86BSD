/* pthread_getconcurrency, pthread_setconcurrency: SUSv2 to SUSv4 */
#define _DEFAULT_SOURCE
#include <errno.h>
#include <pthread.h>

static volatile int level;

int pthread_getconcurrency(void)
{
	return level;
}

int pthread_setconcurrency(int new_level)
{
	if (new_level < 0)
		return EINVAL;
	level = new_level;
	return 0;
}
