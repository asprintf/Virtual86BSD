#!/bin/sh
# genmk.sh - write rules.mk: explicit make rules for every source file.
# POSIX make has no pattern rules or wildcards, so the list of objects
# and their rules are generated.  Run after adding or removing a source
# file (make check verifies that rules.mk is up to date).
#   OBJS         in libc.a and libc.so
#   STATIC_OBJS  only in libc.a (*_static.c)
#   DYN_OBJS     only in libc.so: the dynamic linker (ldso/dyn)
cd "$(dirname "$0")/.." || exit 1
# the sources are in the subdirectories of this directory (aio, ... wstring)
DIRS=$(ls -d */ | sed 's|/$||' | grep -v '^\(build\|config\|tools\)$')
# an archive member is named by the object's basename, and ar -r replaces
# a member of the same name: two sources must not share one
dup=$( { find $DIRS -name '*.c' ! -path 'ldso/dyn/*'; find arch/x86_64 -name '*.s' ! -name '*crt*'; } |
	sed 's|.*/||; s|\.[cs]$||' | sort | uniq -d)
[ -z "$dup" ] || { echo "genmk.sh: sources with the same name (one archive member): $dup" >&2; exit 1; }
objs() {   # objs NAME FILTER: the object list of the sources the filter passes
	printf '%s =' "$1"
	{ find $DIRS -name '*.c'; find arch/x86_64 ldso/dyn -name '*.s' ! -name '*crt*'; } |
	LC_ALL=C sort | while read -r f; do
		case $f in
		ldso/dyn/*) k=DYN_OBJS;;
		*_static.c) k=STATIC_OBJS;;
		*) k=OBJS;;
		esac
		[ "$k" = "$1" ] || continue
		o=$f; printf ' \\\n\t$(B)/obj/%s' "${o%.?}.o"
	done
	echo
}
{
	echo '# Generated by tools/genmk.sh; do not edit.'
	printf 'HDRS ='
	find ../../include $DIRS -name '*.h' | LC_ALL=C sort | while read -r f; do printf ' \\\n\t%s' "$f"; done
	echo
	objs OBJS
	objs STATIC_OBJS
	objs DYN_OBJS
	echo
	find $DIRS -name '*.c' | LC_ALL=C sort | while read -r f; do
		o=${f%.c}.o; d=$(dirname "$o")
		printf '$(B)/obj/%s: %s $(HDRS)\n\tmkdir -p $(B)/obj/%s\n\t$(CC) $(CPPFLAGS) $(CFLAGS) -c -o $@ %s\n\n' "$o" "$f" "$d" "$f"
	done
	find arch/x86_64 ldso/dyn -name '*.s' | LC_ALL=C sort | while read -r f; do
		n=$(basename "$f" .s)
		case $f in
		*/crt*|*/Scrt*|*/rcrt*) o='$(B)/lib/'$n.o; d='$(B)/lib';;
		*)      o='$(B)/obj/'${f%.s}.o; d=$(dirname "$o");;
		esac
		printf '%s: %s\n\tmkdir -p %s\n\t$(AS) -o $@ %s\n\n' "$o" "$f" "$d" "$f"
	done
}
