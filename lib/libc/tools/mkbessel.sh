#!/bin/sh
# mkbessel.sh - write tests/bessel_ref.h: J_n(x) and Y_n(x) to 30 digits,
# computed with bc from the power series (and, for Y_n, the series with
# the digamma function), for s_math.c.  x are doubles given as hex.
cd "$(dirname "$0")/.." || exit 1
{
echo '/* Generated by tools/mkbessel.sh; do not edit.  {n, x, J_n(x), Y_n(x)} */'
for x in 0x1p-10 0x1p-1 0x1p0 0x1.33d152e971b4p1 0x1.ap1 0x1.4p2 0x1.14p3 0x1.4p3 0x1.4p4 0x1.8ep4 0x1.92p4 0x1.ep4 0x1.9p5 0x1.9p6; do
	for n in 0 1 2 5 13 30; do
		m=${x#0x}; e=${m#*p}; m=${m%p*}; i=${m%.*}; f=${m#*.}
		[ "$f" = "$m" ] && f=
		flen=${#f}
		M=$(echo "$i$f" | tr a-f A-F)
		v=$(BC_LINE_LENGTH=0 bc -l <<BC
scale = 300
pi = 4 * a(1)
g = .5772156649015328606065120900824024310421593359399235988057672348848677267776646709369470632917467495
ibase = 16
m = $M
ibase = A
x = m / 2^(4 * $flen)
if ($e >= 0) x = x * 2^$e
if ($e < 0) x = x / 2^(-($e))
n = $n
define f(k) { auto r; r = 1; while (k > 1) { r *= k; k -= 1 }; return r }
define h(k) { auto r, j; r = 0; for (j = 1; j <= k; j++) r += 1 / j; return r }
/* J_n */
y = x / 2; t = y^n / f(n); s = 0
for (k = 0; k < 2000; k++) { s += t; t = -t * y * y / ((k + 1) * (k + 1 + n)); if (t == 0) break }
j = s
/* Y_n */
s1 = 0
for (k = 0; k < n; k++) s1 += f(n - k - 1) / f(k) * y^(2 * k - n)
s2 = 0; t = y^n / f(n); hk = 0; hn = h(n)
for (k = 0; k < 2000; k++) {
	s2 += (-2 * g + hk + hn) * t
	t = -t * y * y / ((k + 1) * (k + 1 + n)); hk += 1 / (k + 1); hn += 1 / (k + 1 + n)
	if (t == 0) break
}
w = 2 / pi * j * l(y) - s1 / pi - s2 / pi
/* in scientific notation: 32 significant digits */
define p(v) {
	auto k, s
	if (v == 0) { print "0"; return 0 }
	s = 1; if (v < 0) { s = -1; v = -v }
	k = 0
	while (v >= 10) { v /= 10; k += 1 }
	while (v < 1) { v *= 10; k -= 1 }
	v = s * v
	scale = 31; v = v / 1; scale = 300
	print v, "e", k
	return 0
}
z = p(j); print " "; z = p(w); print "\n"
BC
)
		set -- $v
		printf '\t{%d, %s, %sL, %sL},\n' "$n" "$x" "$1" "$2"
	done
done
} > tests/bessel_ref.h
