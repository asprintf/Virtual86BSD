/* mkcharsets - make locale/charsets_data.h, the single-byte codesets
 * (their bytes 0x80-0xff as Unicode), with the host's iconv as the
 * reference.  A maintainer's tool; the generated file is part of the
 * sources.
 *
 *   cc -o mkcharsets tools/mkcharsets.c && ./mkcharsets > locale/charsets_data.h */
#include <iconv.h>
#include <stdio.h>
#include <string.h>
#include <stdint.h>

/* canonical name, then aliases (compared without case and punctuation) */
static const char *const sets[][8] = {
	{ "ISO-8859-1", "LATIN1", "L1", "ISO_8859-1:1987", "IBM819", "CP819", "ISO-IR-100" },
	{ "ISO-8859-2", "LATIN2", "L2", "ISO-IR-101" },
	{ "ISO-8859-3", "LATIN3", "L3", "ISO-IR-109" },
	{ "ISO-8859-4", "LATIN4", "L4", "ISO-IR-110" },
	{ "ISO-8859-5", "CYRILLIC", "ISO-IR-144" },
	{ "ISO-8859-6", "ARABIC", "ISO-IR-127", "ECMA-114", "ASMO-708" },
	{ "ISO-8859-7", "GREEK", "GREEK8", "ISO-IR-126", "ECMA-118", "ELOT_928" },
	{ "ISO-8859-8", "HEBREW", "ISO-IR-138" },
	{ "ISO-8859-9", "LATIN5", "L5", "ISO-IR-148" },
	{ "ISO-8859-10", "LATIN6", "L6", "ISO-IR-157" },
	{ "ISO-8859-11" },
	{ "ISO-8859-13", "LATIN7", "L7", "ISO-IR-179" },
	{ "ISO-8859-14", "LATIN8", "L8", "ISO-IR-199", "ISO-CELTIC" },
	{ "ISO-8859-15", "LATIN-9", "LATIN9", "ISO-IR-203" },
	{ "ISO-8859-16", "LATIN10", "L10", "ISO-IR-226" },
	{ "KOI8-R" }, { "KOI8-U" }, { "KOI8-RU" },
	{ "CP1250", "WINDOWS-1250", "MS-EE" },
	{ "CP1251", "WINDOWS-1251", "MS-CYRL" },
	{ "CP1252", "WINDOWS-1252", "MS-ANSI" },
	{ "CP1253", "WINDOWS-1253", "MS-GREEK" },
	{ "CP1254", "WINDOWS-1254", "MS-TURK" },
	{ "CP1256", "WINDOWS-1256", "MS-ARAB" },
	{ "CP1257", "WINDOWS-1257", "WINBALTRIM" },
	{ "IBM437", "CP437", "437" }, { "IBM850", "CP850", "850" }, { "IBM852", "CP852", "852" },
	{ "IBM866", "CP866", "866" },
	{ "MACINTOSH", "MAC", "MACROMAN" },
	{ "TIS-620", "TIS620", "TIS620-0", "ISO-IR-166" },
	{ "CP874", "WINDOWS-874" },
	{ "PT154" }, { "GEORGIAN-PS" }, { "ARMSCII-8" },
};

int main(void)
{
	unsigned i, j, k;
	printf("/* Generated by tools/mkcharsets.c: do not edit. Bytes 0x80-0xff\n"
	       " * of single-byte codesets as Unicode, 0 where undefined. */\n");
	for (i = 0; i < sizeof sets / sizeof *sets; i++) {
		iconv_t cd = iconv_open("UTF-32LE", sets[i][0]);
		uint32_t t[256];
		int ok = 1;
		if (cd == (iconv_t)-1) { fprintf(stderr, "no %s\n", sets[i][0]); return 1; }
		for (j = 0; j < 256; j++) {
			char in = (char)j, *ip = &in;
			uint32_t out = 0;
			char *op = (char *)&out;
			size_t il = 1, ol = 4;
			iconv(cd, 0, 0, 0, 0);
			t[j] = iconv(cd, &ip, &il, &op, &ol) == (size_t)-1 ? 0 : out;
			if (j < 128 && t[j] != j && !(j == 0 && t[j] == 0)) ok = 0;
			if (t[j] > 0xffff) ok = 0;
		}
		iconv_close(cd);
		if (!ok) { fprintf(stderr, "%s: not ASCII below 0x80, or beyond the BMP\n", sets[i][0]); return 1; }
		printf("static const uint16_t cs%u[128] = {", i);
		for (j = 128; j < 256; j++) printf("%s0x%04x,", j % 8 ? " " : "\n\t", t[j]);
		printf("\n};\n");
	}
	printf("static const struct __charset charsets[] = {\n");
	for (i = 0; i < sizeof sets / sizeof *sets; i++) printf("\t{ \"%s\", cs%u },\n", sets[i][0], i);
	printf("};\nstatic const struct { const char *alias; unsigned set; } aliases[] = {\n");
	for (i = 0; i < sizeof sets / sizeof *sets; i++)
		for (k = 1; k < 8 && sets[i][k]; k++) printf("\t{ \"%s\", %u },\n", sets[i][k], i);
	printf("};\n");
	return 0;
}
